// @ts-check
/**
 * Package the browser (Pyodide) combat runtime into `public/battle-runtime/`.
 *
 * The Pyodide worker loads the combat modules from a public URL, not from the server bundle, so the
 * exact Python the browser runs must be a copy of `api/_battle_runtime`. This script computes the
 * transitive import closure of `browser_battle_session.py` (the bridge the worker calls), copies
 * those modules plus the packaged `combat_runtime_data/` (data, tables, manifest) into the Vite
 * `public/` directory, and writes a digest manifest so the worker can attest what it loaded.
 *
 * It never copies Pyodide itself (the worker loads the Pyodide runtime from its own URL) and never
 * copies the game binary or original sheet text - only the modules and the packaged runtime data.
 * Running it repeatedly is idempotent: the target is rebuilt from the source of truth each time.
 *
 * Run:  node scripts/package-browser-battle-runtime.mjs [--out <dir>]
 * Wire: add `"prepare:battle-runtime": "node scripts/package-browser-battle-runtime.mjs"` to
 *       package.json and call it from `predev`/`prebuild`. The default target is
 *       `public/battle-runtime`; `--out` (or BATTLE_RUNTIME_OUT) overrides it for isolated checks.
 */
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP = path.resolve(HERE, "..");
const SOURCE = path.join(APP, "api", "_battle_runtime");
const DATA = path.join(SOURCE, "combat_runtime_data");
function outDir() {
  const flag = process.argv.indexOf("--out");
  const override = flag >= 0 ? process.argv[flag + 1] : process.env.BATTLE_RUNTIME_OUT;
  return path.resolve(APP, override ?? path.join("public", "battle-runtime"));
}
const TARGET = outDir();
const TARGET_DATA = path.join(TARGET, "combat_runtime_data");
const SEED = "browser_battle_session";
const MANIFEST = "browser-runtime-manifest.json";
const SCHEMA = "ka-battle-browser-runtime-1";

const MODULE_RE = /^\s*(?:from\s+([A-Za-z_][A-Za-z0-9_]*)|import\s+([A-Za-z_][A-Za-z0-9_]*(?:\s*,\s*[A-Za-z_][A-Za-z0-9_]*)*))/gm;

function sha256(buffer) {
  return createHash("sha256").update(buffer).digest("hex");
}

function moduleNames(source) {
  const names = new Set();
  for (const match of source.matchAll(MODULE_RE)) {
    for (const name of (match[1] ?? match[2] ?? "").split(",")) {
      const trimmed = name.trim();
      if (trimmed) names.add(trimmed);
    }
  }
  return names;
}

function importClosure() {
  const available = new Set(
    readdirSync(SOURCE).filter((name) => name.endsWith(".py")).map((name) => name.slice(0, -3)),
  );
  const seen = new Set();
  const queue = [SEED];
  while (queue.length > 0) {
    const name = queue.pop();
    if (seen.has(name) || !available.has(name)) continue;
    seen.add(name);
    const source = readFileSync(path.join(SOURCE, `${name}.py`), "utf8");
    for (const dependency of moduleNames(source)) {
      if (available.has(dependency) && !seen.has(dependency)) queue.push(dependency);
    }
  }
  return [...seen].sort();
}

function walkFiles(root) {
  const files = [];
  for (const entry of readdirSync(root, { withFileTypes: true })) {
    const absolute = path.join(root, entry.name);
    if (entry.isDirectory()) files.push(...walkFiles(absolute));
    else if (entry.isFile()) files.push(absolute);
  }
  return files.sort();
}

function main() {
  if (!existsSync(path.join(SOURCE, `${SEED}.py`))) {
    throw new Error(`combat bridge missing: ${path.join(SOURCE, `${SEED}.py`)}`);
  }
  if (!existsSync(path.join(DATA, "runtime-manifest.json"))) {
    throw new Error(`packaged combat runtime data missing: ${DATA}`);
  }
  if (!statSync(SOURCE).isDirectory() || !statSync(DATA).isDirectory()) {
    throw new Error("combat runtime source is not a directory");
  }
  const modules = importClosure();
  rmSync(TARGET, { recursive: true, force: true });
  mkdirSync(TARGET, { recursive: true });
  const files = {};
  for (const name of modules) {
    const file = `${name}.py`;
    const bytes = readFileSync(path.join(SOURCE, file));
    writeFileSync(path.join(TARGET, file), bytes);
    files[`battle-runtime/${file}`] = sha256(bytes);
  }
  cpSync(DATA, TARGET_DATA, { recursive: true });
  for (const absolute of walkFiles(TARGET_DATA)) {
    const relative = path.relative(TARGET, absolute).split(path.sep).join("/");
    files[`battle-runtime/${relative}`] = sha256(readFileSync(absolute));
  }
  const manifest = {
    schema: SCHEMA,
    entry: `${SEED}.py`,
    seed: SEED,
    modules,
    source: "api/_battle_runtime",
    note: "Generated by scripts/package-browser-battle-runtime.mjs; do not edit the copy by hand.",
    files,
  };
  writeFileSync(path.join(TARGET, MANIFEST), `${JSON.stringify(manifest, null, 2)}\n`);
  process.stdout.write(
    `${JSON.stringify({ schema: SCHEMA, target: path.relative(APP, TARGET), modules: modules.length, files: Object.keys(files).length })}\n`,
  );
}

main();
