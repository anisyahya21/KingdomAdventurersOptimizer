function ensureAvailable(view, offset, needed, label) {
  if (offset + needed > view.byteLength) {
    throw new Error(`Unexpected end of map binary while reading ${label}`);
  }
}

function parseMapBinarySectionA(bytes) {
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  const BYTES_PER_U32 = 4;
  const HEADER_BYTES = 8;
  const CELL_BYTES = 24;
  const ROW_SENTINEL_BYTES = 4;

  if (view.byteLength < HEADER_BYTES) {
    throw new Error(`Map binary too small: ${view.byteLength} bytes`);
  }

  let offset = 0;
  const width = view.getUint32(offset, false);
  offset += BYTES_PER_U32;
  const height = view.getUint32(offset, false);
  offset += BYTES_PER_U32;

  const cells = [];
  for (let y = 0; y < height; y += 1) {
    for (let x = 0; x < width; x += 1) {
      ensureAvailable(view, offset, CELL_BYTES, `cell ${x},${y}`);
      const f0 = view.getUint32(offset, false);
      const f1 = view.getUint32(offset + 4, false);
      const f2 = view.getUint32(offset + 8, false);
      const f3 = view.getUint32(offset + 12, false);
      const f4 = view.getUint32(offset + 16, false);
      const f5 = view.getUint32(offset + 20, false);
      offset += CELL_BYTES;
      cells.push({ x, y, fields: { f0, f1, f2, f3, f4, f5 } });
    }

    ensureAvailable(view, offset, ROW_SENTINEL_BYTES, `row sentinel ${y}`);
    const sentinel = view.getUint32(offset, false);
    offset += ROW_SENTINEL_BYTES;
    if (sentinel !== width) {
      throw new Error(`Invalid row sentinel at row ${y}: expected ${width}, got ${sentinel}`);
    }
  }

  return { width, height, cells };
}

function parseCsvLine(line) {
  const out = [];
  let current = "";
  let inQuotes = false;

  for (let i = 0; i < line.length; i += 1) {
    const ch = line[i];

    if (ch === '"') {
      const next = line[i + 1];
      if (inQuotes && next === '"') {
        current += '"';
        i += 1;
      } else {
        inQuotes = !inQuotes;
      }
      continue;
    }

    if (ch === "," && !inQuotes) {
      out.push(current);
      current = "";
      continue;
    }

    current += ch;
  }

  out.push(current);
  return out;
}

function parseCsv(text) {
  const lines = text
    .replace(/^\uFEFF/, "")
    .split(/\r?\n/)
    .filter((line) => line.trim().length > 0);

  if (lines.length === 0) {
    return [];
  }

  const header = parseCsvLine(lines[0]);
  const rows = [];

  for (let i = 1; i < lines.length; i += 1) {
    const cols = parseCsvLine(lines[i]);
    const row = {};
    for (let c = 0; c < header.length; c += 1) {
      const key = header[c] === "" ? `__col_${c}` : header[c];
      row[key] = cols[c] ?? "";
    }
    rows.push(row);
  }

  return rows;
}

function toInt(value) {
  if (value === undefined || value === null || value === "") {
    return null;
  }
  const parsed = Number.parseInt(String(value), 10);
  return Number.isNaN(parsed) ? null : parsed;
}

function mapSemanticGroup(kind) {
  if (kind === "terrain-ground" || kind === "terrain-water") {
    return "terrain/ground/water";
  }
  if (kind === "road-path-traffic-buildable") {
    return "road/path/traffic/buildable-related";
  }
  if (kind === "special-overlay-runtime-marker") {
    return "special overlay/runtime-marker";
  }
  return "unknown";
}

function formatFixture(metaByChipId, observedIds, generatedAt, sourceJsonPath) {
  const sortedIds = [...observedIds].sort((a, b) => a - b);

  return `/* eslint-disable */
// Auto-generated by scripts/export-f2-semantic-layer-fixture.mjs
// generatedAt: ${generatedAt}
// source: ${sourceJsonPath.replace(/\\/g, "/")}

export type F2SemanticGroup =
  | "terrain/ground/water"
  | "road/path/traffic/buildable-related"
  | "special overlay/runtime-marker"
  | "unknown";

export interface F2MapChipRuntimeMeta {
  readonly chipId: number;
  readonly semanticGroup: F2SemanticGroup;
  readonly type: number | null;
  readonly category: number | null;
  readonly movementCost: number | null;
  readonly targetCost: number | null;
  readonly layer: number | null;
  readonly sizeWidth: number | null;
  readonly sizeHeight: number | null;
  readonly flags: readonly string[];
  readonly relatedDataType: number | null;
  readonly relatedDataId: number | null;
  readonly f3Distribution: Readonly<Record<number, number>>;
  readonly f4Distribution: Readonly<Record<number, number>>;
}

export const OBSERVED_F2_MAPCHIP_IDS: readonly number[] = ${JSON.stringify(sortedIds, null, 2)};

export const F2_RUNTIME_META_BY_ID: Readonly<Record<number, F2MapChipRuntimeMeta>> = ${JSON.stringify(metaByChipId, null, 2)};

const UNKNOWN_GROUP: F2SemanticGroup = "unknown";

export function getF2SemanticGroup(chipId: number): F2SemanticGroup {
  return F2_RUNTIME_META_BY_ID[chipId]?.semanticGroup ?? UNKNOWN_GROUP;
}

export function isF2RoadLike(chipId: number): boolean {
  return getF2SemanticGroup(chipId) === "road/path/traffic/buildable-related";
}

export function isF2TerrainLike(chipId: number): boolean {
  return getF2SemanticGroup(chipId) === "terrain/ground/water";
}

export function isF2SpecialOverlay(chipId: number): boolean {
  return getF2SemanticGroup(chipId) === "special overlay/runtime-marker";
}

export function getF2MapChipRuntimeMeta(chipId: number): F2MapChipRuntimeMeta | null {
  return F2_RUNTIME_META_BY_ID[chipId] ?? null;
}
`;
}

function run() {
  const projectRoot = process.cwd();
  const repoRoot = path.resolve(projectRoot, "..", "..");

  const sectionAAnalysisPath = path.resolve(projectRoot, "tmp", "map-section-a-analysis.json");
  const f2SemanticJsonPath = path.resolve(projectRoot, "tmp", "map-section-a-f2-mapchip-semantic-groups.json");
  const mapChipPath = path.resolve(repoRoot, "data", "sheet-research", "raw-copies", "KA GameData - MapChip.csv");

  for (const required of [sectionAAnalysisPath, f2SemanticJsonPath, mapChipPath]) {
    if (!fs.existsSync(required)) {
      throw new Error(`Missing required file: ${required}`);
    }
  }

  const sectionAAnalysis = JSON.parse(fs.readFileSync(sectionAAnalysisPath, "utf8"));
  const f2SemanticReport = JSON.parse(fs.readFileSync(f2SemanticJsonPath, "utf8"));

  const mapBytes = fs.readFileSync(sectionAAnalysis.sourceMapPath);
  const parsedMap = parseMapBinarySectionA(mapBytes);
  const observedIdsFromMap = new Set(parsedMap.cells.map((cell) => cell.fields.f2));

  const mapChipRows = parseCsv(fs.readFileSync(mapChipPath, "utf8"));
  const mapChipById = new Map();
  for (const row of mapChipRows) {
    const id = toInt(row.id ?? row.__col_0);
    if (id !== null) {
      mapChipById.set(id, row);
    }
  }

  const reportEntries = f2SemanticReport.entries ?? [];
  const observedIdsFromReport = new Set(reportEntries.map((entry) => entry.f2));

  for (const id of observedIdsFromMap) {
    if (!observedIdsFromReport.has(id)) {
      throw new Error(`Observed map f2 id ${id} missing from semantic report entries`);
    }
    if (!mapChipById.has(id)) {
      throw new Error(`Observed map f2 id ${id} missing from MapChip.csv`);
    }
  }

  const metaByChipId = {};

  for (const entry of reportEntries) {
    const chipId = entry.f2;
    const chip = mapChipById.get(chipId) ?? null;

    const f3Distribution = {};
    for (const row of entry.f3Distribution ?? []) {
      f3Distribution[row.value] = row.count;
    }

    const f4Distribution = {};
    for (const row of entry.f4Distribution ?? []) {
      f4Distribution[row.value] = row.count;
    }

    const metadata = {
      chipId,
      semanticGroup: mapSemanticGroup(entry.semanticKind),
      type: entry.mapChip?.type ?? toInt(chip?.type),
      category: entry.mapChip?.category ?? toInt(chip?.category),
      movementCost: entry.mapChip?.movementCost ?? toInt(chip?.movementCost),
      targetCost: entry.mapChip?.targetCost ?? toInt(chip?.targetCost),
      layer: entry.mapChip?.layer ?? toInt(chip?.layer),
      sizeWidth: entry.mapChip?.sizeWidth ?? toInt(chip?.sizeWidth),
      sizeHeight: entry.mapChip?.sizeHeight ?? toInt(chip?.sizeHeight),
      flags: entry.flags ?? [],
      relatedDataType: entry.mapChip?.relatedDataType ?? toInt(chip?.relatedDataType),
      relatedDataId: entry.mapChip?.relatedDataId ?? toInt(chip?.relatedDataId),
      f3Distribution,
      f4Distribution,
    };

    metaByChipId[chipId] = metadata;
  }

  const outPath = path.resolve(projectRoot, "src", "runtime", "world-builder", "fixtures", "f2-semantic-layer.ts");
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(
    outPath,
    formatFixture(metaByChipId, observedIdsFromMap, new Date().toISOString(), f2SemanticJsonPath),
    "utf8",
  );

  const summary = {
    output: outPath,
    observedCount: observedIdsFromMap.size,
    semanticCounts: {
      terrainLike: Object.values(metaByChipId).filter((meta) => meta.semanticGroup === "terrain/ground/water").length,
      roadLike: Object.values(metaByChipId).filter((meta) => meta.semanticGroup === "road/path/traffic/buildable-related").length,
      specialOverlay: Object.values(metaByChipId).filter((meta) => meta.semanticGroup === "special overlay/runtime-marker").length,
      unknown: Object.values(metaByChipId).filter((meta) => meta.semanticGroup === "unknown").length,
    },
  };

  console.log(JSON.stringify(summary, null, 2));
  console.log(`Wrote ${outPath}`);
}

run();
